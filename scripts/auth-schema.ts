// Writes Better Auth's tables as plain SQL. Run against an EMPTY database, or it emits only
// the difference (Brain: better-auth). Usage: pnpm db:auth-schema
import { writeFileSync } from "node:fs";
import { getMigrations } from "better-auth/db/migration";
import { Pool } from "pg";
import { authOptions } from "../lib/auth-options";

const db = new Pool({ connectionString: process.env.DATABASE_URL });
const options = authOptions({ db, baseURL: "http://localhost:3000", secret: "x".repeat(32), sendCode: async () => {} });
const { compileMigrations } = await getMigrations(options as never);
const sql = await compileMigrations();
writeFileSync("db/migrations/0001_auth.sql", `-- Generated by scripts/auth-schema.ts (better-auth 1.7.5). Do not edit by hand.\n${sql}\n`);
await db.end();
console.log("wrote db/migrations/0001_auth.sql");
